// Generates supabase/setup.sql — the one-paste bootstrap for the Supabase
// SQL Editor — from supabase/migrations/ and the expert roster, so it can
// never drift from the migrations again. `pnpm test` fails when the
// committed file is stale; regenerate with `pnpm db:setup-sql`.
//
// Each migration runs once, recorded in supabase_migrations.schema_migrations
// (the table the Supabase CLI uses), so re-running the file is safe and a
// later `supabase db push` sees the same history.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { EXPERT_ROSTER } from "@/seed/experts";

const ROOT = path.resolve(import.meta.dirname, "..");
const MIGRATIONS = path.join(ROOT, "supabase", "migrations");
export const SETUP_SQL_PATH = path.join(ROOT, "supabase", "setup.sql");

const literal = (value: string | null) => (value === null ? "null" : `'${value.replace(/'/g, "''")}'`);

function migrationBlock(file: string, body: string): string {
  const [version, ...rest] = file.replace(/\.sql$/, "").split("_");
  const tag = `$migration_${version}$`;
  if (body.includes(tag)) throw new Error(`${file} contains the reserved delimiter ${tag}`);
  return [
    `-- ${file}`,
    `do $apply$ begin`,
    `  if not exists (select 1 from supabase_migrations.schema_migrations where version = ${literal(version)}) then`,
    `    execute ${tag}`,
    // The whole file is one transaction; a migration's own begin/commit can't run inside it.
    body.replace(/^\s*(begin|commit);\s*$/gim, "").trim(),
    `${tag};`,
    `    insert into supabase_migrations.schema_migrations (version, name, statements) values (${literal(version)}, ${literal(rest.join("_"))}, '{}');`,
    `  end if;`,
    `end $apply$;`,
  ].join("\n");
}

function rosterBlock(): string {
  const experts = EXPERT_ROSTER.map((expert) =>
    `  (${literal(expert.slug)}, ${literal(expert.displayName)}, ${literal(expert.xHandle)}, ${literal(expert.headline ?? null)}, ${literal(expert.primaryCategorySlug)}, 'unverified')`);
  const links = EXPERT_ROSTER.flatMap((expert) => expert.categorySlugs.map((slug) =>
    `  ((select id from public.experts where slug = ${literal(expert.slug)}), ${literal(slug)})`));
  return [
    "-- Expert roster (seed/experts.ts). X identities stay unverified until the official API resolves them.",
    "insert into public.experts (slug, display_name, x_handle, headline, primary_category_slug, source_status) values",
    `${experts.join(",\n")}`,
    "on conflict (slug) do nothing;",
    "insert into public.expert_categories (expert_id, category_slug) values",
    `${links.join(",\n")}`,
    "on conflict do nothing;",
  ].join("\n");
}

export function buildSetupSql(): string {
  const files = readdirSync(MIGRATIONS).filter((file) => /^\d+_.+\.sql$/.test(file)).sort();
  const header = `-- ============================================================================
-- PublicLedger one-shot setup. GENERATED by scripts/build-setup-sql.ts from
-- supabase/migrations/ and seed/experts.ts. Do not edit by hand: run
-- \`pnpm db:setup-sql\` after adding a migration.
--
-- Paste into Supabase Dashboard -> SQL Editor -> New Query -> Run. Safe to
-- re-run: each migration is applied once and recorded in
-- supabase_migrations.schema_migrations, like \`supabase db push\`.
-- Contains the schema and categories (${files.length} migrations) and the
-- ${EXPERT_ROSTER.length}-expert roster. Zero predictions, fabricated or otherwise.
-- ============================================================================`;
  const tracker = `create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);

-- A database bootstrapped by an older, hand-written setup.sql has the schema
-- but no migration history; replaying migrations onto it would fail half-way.
do $guard$ begin
  if to_regclass('public.predictions') is not null
    and not exists (select 1 from supabase_migrations.schema_migrations) then
    raise exception 'This database was created by an older setup.sql and has no migration history. Record what it already has with "supabase migration repair --status applied <version>" for each migration it contains, then run "supabase db push".';
  end if;
end $guard$;`;
  return [
    header,
    "",
    "begin;",
    "",
    tracker,
    "",
    ...files.map((file) => `${migrationBlock(file, readFileSync(path.join(MIGRATIONS, file), "utf8"))}\n`),
    rosterBlock(),
    "",
    "commit;",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(SETUP_SQL_PATH, buildSetupSql());
  console.log(`Wrote ${path.relative(ROOT, SETUP_SQL_PATH)}`);
}
